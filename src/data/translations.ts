/**
 * Proxy object so existing `TRANSLATIONS[language]` calls continue to work seamlessly
 * while always resolving the current active location dynamically.
 */
export const TRANSLATIONS = new Proxy(
  {} as Record<Language, ReturnType<typeof getTranslations>>,
  {
    get(_target, prop: string) {
      if (prop === 'EN' || prop === 'DE') {
        return getTranslations(prop as Language);
      }
      return undefined;
    },
  }
);
